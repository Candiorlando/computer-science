// ─── recordCaseNoteEvent ───────────────────────────────────────────────

export function recordCaseNoteEvent(event: CaseNoteEvent) {
  const sessionAt = event.sessionAt ?? new Date().toISOString();
  const note: CaseNote = {
    id: newId(),
    participantType: event.participantType,
    sessionAt,
    generatedAt: new Date().toISOString(),
    autoGenerated: true,
    eventKind: event.kind,
    sourceArtifactId: event.sourceArtifactId,
    activityType: activityLabel(event.kind),
    toolUsed: toolRoute(event.kind),
    ...(event.participantType === "individual-client"
      ? {
          clientCaseId: event.caseId,
          clientName: event.clientName,
        }
      : event.participantType === "business-vendor"
        ? {
            businessOrgId: event.orgId,
            businessOrgName: event.orgName,
            clientName: event.requesterName,
          }
        : {
            partnerOrgId: event.partnerOrgId,
            partnerOrgName: event.partnerOrgName,
            clientName: event.actorName,
            // If the partner event references a linked client case
            clientCaseId:
              "caseId" in event ? event.caseId : undefined,
          }),
    ...buildDap(event),
  };
  appendCaseNote(note);
  return note;
}

