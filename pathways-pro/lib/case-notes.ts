    "ocr-doj-complaint-generated": "OCR / DOJ Civil Rights Complaint Draft",
    "interest-profiler-completed": "Interest Profiler — Mini-IPIP + RIASEC",
    "tsa-completed": "Transferable Skills Analysis",
