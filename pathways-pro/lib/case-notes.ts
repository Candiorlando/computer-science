"use client";

// Automated Case Documentation Auditor
//
// Every artifact a client or business vendor generates on the platform
// fires a typed event into recordCaseNoteEvent(). A template builds a
// DAP-format case note from the event payload — objective, factual,
// VR-documentation-standard — and persists it to localStorage. The
// counselor sees these notes on the client's /report and on the
// Business View dashboard.
//
// Notes are deterministic templates, not AI-generated, so they're
// reproducible at audit time and free to render.

// ─── Types ─────────────────────────────────────────────────────────────

export type ParticipantType =
  | "individual-client"
  | "business-vendor"
  | "employment-partner";

export type CaseNoteEventKind =
  // Module 1 — Self-Employment (individual client)
  | "concept-match-generated"
  | "business-plan-generated"
  // Module 2 — Self Advocacy (individual client)
  | "accommodation-letter-generated"
  | "problem-analysis-generated"
  | "eeoc-charge-generated"
  | "ocr-doj-complaint-generated"
  // Existing assessment / planning artifacts (individual client)
  | "interest-profiler-completed"
  | "tsa-completed"
  | "ipe-signed"
  | "resume-generated"
  // Business vendor / employer
  | "business-service-requested"
  | "business-service-approved"
  | "business-service-declined"
  | "business-service-released"
  // Employment Partner
  | "partner-opportunity-posted"
  | "partner-ce-selected"
  | "partner-ce-stage-advanced"
  | "partner-accommodation-inquiry"
  | "partner-placement-offered"
  | "partner-placement-accepted"
  | "partner-progress-update"
  | "partner-document-uploaded";

export interface CaseNote {
  id: string;
  // Subject
  participantType: ParticipantType;
  clientCaseId?: string;
  clientName?: string;
  businessOrgId?: string;
  businessOrgName?: string;
  partnerOrgId?: string;
  partnerOrgName?: string;
  // Metadata
  sessionAt: string;       // when the activity happened
  activityType: string;    // human-readable, e.g. "ADA Accommodation Draft"
  toolUsed: string;        // route or tool name
  eventKind: CaseNoteEventKind;
  // DAP body
  data: string;
  assessment: string;
  plan: string;
  // Provenance
  generatedAt: string;
  authorEmail?: string;    // for manual notes; null for auto-generated
  autoGenerated: boolean;
  sourceArtifactId?: string;
}

// ─── Storage ───────────────────────────────────────────────────────────

const KEY = "pathways-pro:case-notes-v1";

export function loadCaseNotes(): CaseNote[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = window.localStorage.getItem(KEY);
    return raw ? (JSON.parse(raw) as CaseNote[]) : [];
  } catch {
    return [];
  }
}

export function saveCaseNotes(list: CaseNote[]) {
  if (typeof window === "undefined") return;
  window.localStorage.setItem(KEY, JSON.stringify(list));
}

export function appendCaseNote(note: CaseNote) {
  saveCaseNotes([note, ...loadCaseNotes()]);
}

export function notesForClient(caseId: string): CaseNote[] {
  return loadCaseNotes()
    .filter((n) => n.clientCaseId === caseId)
    .sort((a, b) => Date.parse(b.sessionAt) - Date.parse(a.sessionAt));
}

export function notesForBusinessOrg(orgId: string): CaseNote[] {
  return loadCaseNotes()
    .filter((n) => n.businessOrgId === orgId)
    .sort((a, b) => Date.parse(b.sessionAt) - Date.parse(a.sessionAt));
}

export function notesForPartnerOrg(orgId: string): CaseNote[] {
  return loadCaseNotes()
    .filter((n) => n.partnerOrgId === orgId)
    .sort((a, b) => Date.parse(b.sessionAt) - Date.parse(a.sessionAt));
}

export function notesForCounselor(emails: {
  clientCaseIds?: string[];
  businessOrgIds?: string[];
}): CaseNote[] {
  return loadCaseNotes()
    .filter(
      (n) =>
        (n.clientCaseId && emails.clientCaseIds?.includes(n.clientCaseId)) ||
        (n.businessOrgId && emails.businessOrgIds?.includes(n.businessOrgId)),
    )
    .sort((a, b) => Date.parse(b.sessionAt) - Date.parse(a.sessionAt));
}

function newId(): string {
  return "note-" + Math.random().toString(36).slice(2, 10);
}

